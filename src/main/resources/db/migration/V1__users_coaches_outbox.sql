CREATE TABLE users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 public_id UUID NOT NULL UNIQUE,
 email VARCHAR(254), phone VARCHAR(16), password_hash VARCHAR(2048) NOT NULL,
 display_name VARCHAR(121) NOT NULL, avatar_url VARCHAR(255), birth_date DATE, gender VARCHAR(16),
 role VARCHAR(16) NOT NULL CHECK(role IN ('ATHLETE','COACH','ADMIN')),
 status VARCHAR(16) NOT NULL CHECK(status IN ('ACTIVE','SUSPENDED')),
 email_verified BOOLEAN NOT NULL DEFAULT FALSE, phone_verified BOOLEAN NOT NULL DEFAULT FALSE,
 credential_version BIGINT NOT NULL DEFAULT 1 CHECK(credential_version>0),
 credentials_changed_at TIMESTAMPTZ NOT NULL,
 aggregate_version BIGINT NOT NULL DEFAULT 0 CHECK(aggregate_version>=0),
 created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL, version BIGINT NOT NULL DEFAULT 0,
 CHECK(email IS NOT NULL OR phone IS NOT NULL), CHECK(email IS NULL OR email=lower(btrim(email)))
);
CREATE UNIQUE INDEX users_email_lower_uq ON users(lower(email)) WHERE email IS NOT NULL;
CREATE UNIQUE INDEX users_phone_uq ON users(phone) WHERE phone IS NOT NULL;
CREATE TABLE coach_profiles (
 user_id BIGINT PRIMARY KEY REFERENCES users(id), display_name VARCHAR(60) NOT NULL,
 headline VARCHAR(120), bio VARCHAR(3000) NOT NULL, specialties TEXT NOT NULL,
 experience_years INTEGER NOT NULL CHECK(experience_years BETWEEN 0 AND 60), certifications TEXT NOT NULL,
 instagram_handle VARCHAR(30), result_image_urls TEXT NOT NULL,
 status VARCHAR(16) NOT NULL CHECK(status IN ('PENDING','APPROVED','REJECTED')), rejection_reason VARCHAR(500),
 created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL, version BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX coach_status_idx ON coach_profiles(status,created_at,user_id);
CREATE TABLE outbox (
 id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 event_id UUID NOT NULL UNIQUE, aggregate_id UUID NOT NULL, aggregate_version BIGINT NOT NULL CHECK(aggregate_version>0),
 payload TEXT NOT NULL, occurred_at TIMESTAMPTZ NOT NULL, published_at TIMESTAMPTZ,
 attempts INTEGER NOT NULL DEFAULT 0, available_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 lease_token UUID, lease_until TIMESTAMPTZ,
 UNIQUE(aggregate_id,aggregate_version)
);
CREATE INDEX outbox_pending_idx ON outbox(id) WHERE published_at IS NULL;
