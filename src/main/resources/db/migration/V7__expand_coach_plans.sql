-- Expand the plan schema and convert existing plan references to numeric keys.
ALTER TABLE coach_plans
    DROP CONSTRAINT coach_plans_status_check,
    DROP CONSTRAINT coach_plans_price_check,
    DROP CONSTRAINT coach_plans_duration_days_check;

ALTER TABLE coach_plans RENAME COLUMN status TO is_active;
ALTER TABLE coach_plans RENAME COLUMN price TO price_rial;

ALTER TABLE coach_plans
    ADD COLUMN id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    ADD COLUMN coach_user_id BIGINT,
    ADD COLUMN summary VARCHAR(180),
    ADD COLUMN compare_at_price_rial BIGINT,
    ADD COLUMN first_delivery_days INTEGER,
    ADD COLUMN is_recommended BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN display_order INTEGER NOT NULL DEFAULT 0,
    ALTER COLUMN is_active TYPE BOOLEAN USING (is_active = 'ACTIVE'),
    ALTER COLUMN title TYPE VARCHAR(100),
    ALTER COLUMN description TYPE TEXT;

UPDATE coach_plans AS plan
SET coach_user_id = profile.user_id
FROM users AS account
JOIN coach_profiles AS profile ON profile.user_id = account.id
WHERE account.public_id = plan.coach_id;

ALTER TABLE coach_plans
    ALTER COLUMN coach_user_id SET NOT NULL,
    ALTER COLUMN is_active SET DEFAULT FALSE,
    ADD CONSTRAINT coach_plans_coach_user_fkey
        FOREIGN KEY (coach_user_id) REFERENCES coach_profiles (user_id),
    ADD CONSTRAINT coach_plans_price_rial_check CHECK (price_rial >= 0),
    ADD CONSTRAINT coach_plans_compare_at_price_check
        CHECK (compare_at_price_rial > price_rial),
    ADD CONSTRAINT coach_plans_duration_days_check CHECK (duration_days > 0),
    ADD CONSTRAINT coach_plans_first_delivery_days_check CHECK (first_delivery_days >= 0),
    ADD CONSTRAINT coach_plans_display_order_check CHECK (display_order >= 0);

ALTER TABLE coach_plan_includes ADD COLUMN numeric_plan_id BIGINT;
ALTER TABLE plan_subscriptions
    ADD COLUMN id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    ADD COLUMN numeric_plan_id BIGINT,
    ADD COLUMN numeric_coach_id BIGINT,
    ADD COLUMN numeric_athlete_id BIGINT;

-- An existing order needs the real numeric ID from Order to preserve payment routing.
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM plan_subscriptions WHERE order_id IS NOT NULL) THEN
        RAISE EXCEPTION 'Cannot migrate plan subscriptions with existing order references'
            USING HINT = 'Reconcile existing orders with their numeric IDs before applying V7.';
    END IF;
END;
$$;

UPDATE coach_plan_includes AS included
SET numeric_plan_id = plan.id
FROM coach_plans AS plan
WHERE included.plan_id = plan.plan_id;

UPDATE plan_subscriptions AS subscription
SET numeric_plan_id = plan.id,
    numeric_coach_id = plan.coach_user_id,
    numeric_athlete_id = athlete.id
FROM coach_plans AS plan, users AS athlete
WHERE subscription.plan_id = plan.plan_id
  AND subscription.coach_id = plan.coach_id
  AND subscription.athlete_id = athlete.public_id;

-- Unresolvable legacy identities must fail before the old columns are removed.
ALTER TABLE coach_plan_includes ALTER COLUMN numeric_plan_id SET NOT NULL;
ALTER TABLE plan_subscriptions
    ALTER COLUMN numeric_plan_id SET NOT NULL,
    ALTER COLUMN numeric_coach_id SET NOT NULL,
    ALTER COLUMN numeric_athlete_id SET NOT NULL,
    ALTER COLUMN order_id TYPE BIGINT USING (order_id::text::BIGINT);

ALTER TABLE coach_plan_includes DROP COLUMN plan_id;
ALTER TABLE plan_subscriptions
    DROP COLUMN subscription_id,
    DROP COLUMN plan_id,
    DROP COLUMN coach_id,
    DROP COLUMN athlete_id;

ALTER TABLE coach_plans DROP COLUMN plan_id, DROP COLUMN coach_id;
ALTER TABLE coach_plans ADD CONSTRAINT coach_plans_pkey PRIMARY KEY (id);

ALTER TABLE coach_plan_includes RENAME COLUMN numeric_plan_id TO plan_id;
ALTER TABLE coach_plan_includes
    ADD CONSTRAINT coach_plan_includes_pkey PRIMARY KEY (plan_id, include_key),
    ADD CONSTRAINT coach_plan_includes_plan_id_fkey
        FOREIGN KEY (plan_id) REFERENCES coach_plans (id) ON DELETE CASCADE;

ALTER TABLE plan_subscriptions RENAME COLUMN numeric_plan_id TO plan_id;
ALTER TABLE plan_subscriptions RENAME COLUMN numeric_coach_id TO coach_id;
ALTER TABLE plan_subscriptions RENAME COLUMN numeric_athlete_id TO athlete_id;
ALTER TABLE plan_subscriptions
    ADD CONSTRAINT plan_subscriptions_pkey PRIMARY KEY (id),
    ADD CONSTRAINT plan_subscriptions_plan_id_fkey
        FOREIGN KEY (plan_id) REFERENCES coach_plans (id),
    ADD CONSTRAINT plan_subscriptions_coach_id_fkey
        FOREIGN KEY (coach_id) REFERENCES coach_profiles (user_id),
    ADD CONSTRAINT plan_subscriptions_athlete_id_fkey
        FOREIGN KEY (athlete_id) REFERENCES users (id),
    ADD CONSTRAINT plan_subscriptions_distinct_accounts_check CHECK (coach_id <> athlete_id),
    ADD CONSTRAINT plan_subscriptions_order_id_check CHECK (order_id > 0);

CREATE INDEX coach_plans_coach ON coach_plans (coach_user_id, created_at DESC);
CREATE INDEX coach_plans_coach_display_idx ON coach_plans (coach_user_id, display_order, id);
CREATE INDEX coach_plans_coach_active_price_idx ON coach_plans (coach_user_id, price_rial)
    WHERE is_active;
CREATE UNIQUE INDEX coach_plans_one_recommended_per_coach_idx ON coach_plans (coach_user_id)
    WHERE is_recommended;
CREATE INDEX plan_subscriptions_plan_id_idx ON plan_subscriptions (plan_id);
CREATE INDEX plan_subscriptions_athlete ON plan_subscriptions (athlete_id, created_at DESC);
CREATE INDEX plan_subscriptions_coach ON plan_subscriptions (coach_id, status);

CREATE TABLE plan_feature_catalog (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(64) NOT NULL UNIQUE CHECK (code <> '' AND code = btrim(code)),
    title VARCHAR(100) NOT NULL CHECK (btrim(title) <> ''),
    description TEXT,
    category VARCHAR(24) NOT NULL CHECK (btrim(category) <> ''),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    display_order INTEGER NOT NULL DEFAULT 0 CHECK (display_order >= 0),
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL
);

CREATE INDEX plan_feature_catalog_active_order_idx
    ON plan_feature_catalog (category, display_order, id) WHERE is_active;

CREATE TABLE coach_plan_features (
    plan_id BIGINT NOT NULL,
    feature_id BIGINT NOT NULL,
    PRIMARY KEY (plan_id, feature_id),
    CONSTRAINT coach_plan_features_plan_fkey
        FOREIGN KEY (plan_id) REFERENCES coach_plans (id) ON DELETE CASCADE,
    CONSTRAINT coach_plan_features_feature_fkey
        FOREIGN KEY (feature_id) REFERENCES plan_feature_catalog (id)
);

CREATE INDEX coach_plan_features_feature_idx ON coach_plan_features (feature_id, plan_id);

CREATE TABLE plan_field_definitions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    feature_id BIGINT,
    code VARCHAR(64) NOT NULL UNIQUE CHECK (code <> '' AND code = btrim(code)),
    label VARCHAR(100) NOT NULL CHECK (btrim(label) <> ''),
    help_text TEXT,
    value_type VARCHAR(20) NOT NULL CHECK (value_type IN ('INTEGER', 'SINGLE_SELECT', 'MULTI_SELECT')),
    validation_rules JSONB NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(validation_rules) = 'object'),
    is_required BOOLEAN NOT NULL DEFAULT FALSE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    display_order INTEGER NOT NULL DEFAULT 0 CHECK (display_order >= 0),
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT plan_field_definitions_feature_fkey
        FOREIGN KEY (feature_id) REFERENCES plan_feature_catalog (id)
);

CREATE INDEX plan_field_definitions_feature_order_idx
    ON plan_field_definitions (feature_id, display_order, id);

CREATE TABLE coach_plan_field_values (
    plan_id BIGINT NOT NULL,
    field_id BIGINT NOT NULL,
    value JSONB NOT NULL CHECK (jsonb_typeof(value) IN ('number', 'string', 'array')),
    PRIMARY KEY (plan_id, field_id),
    CONSTRAINT coach_plan_field_values_plan_fkey
        FOREIGN KEY (plan_id) REFERENCES coach_plans (id) ON DELETE CASCADE,
    CONSTRAINT coach_plan_field_values_field_fkey
        FOREIGN KEY (field_id) REFERENCES plan_field_definitions (id)
);

CREATE INDEX coach_plan_field_values_field_idx ON coach_plan_field_values (field_id, plan_id);

CREATE TABLE coach_plan_levels (
    plan_id BIGINT NOT NULL,
    level VARCHAR(16) NOT NULL CHECK (level IN ('BEGINNER', 'INTERMEDIATE', 'ADVANCED', 'PROFESSIONAL')),
    PRIMARY KEY (plan_id, level),
    CONSTRAINT coach_plan_levels_plan_fkey
        FOREIGN KEY (plan_id) REFERENCES coach_plans (id) ON DELETE CASCADE
);

CREATE INDEX coach_plan_levels_level_idx ON coach_plan_levels (level, plan_id);
