CREATE TABLE plan_include_catalog (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(64) NOT NULL UNIQUE CHECK (code <> '' AND code = btrim(code)),
    label VARCHAR(100) NOT NULL CHECK (btrim(label) <> ''),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    display_order INTEGER NOT NULL DEFAULT 0 CHECK (display_order >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX plan_include_catalog_active_order_idx
    ON plan_include_catalog (display_order, id) WHERE is_active;

